# 2. الفحص الأخلاقي (حلال 100%)
forbidden_words = ["عنف", "مخل", "قمار", "مراهنات", "غير لائق", "إيحاء"]

def check_ethics(text):
    for word in forbidden_words:
        if word in text:
            return False
    return True

def run_cloud_qazo():
    series_choice = random.choice(list(series_database.keys()))
    topic = random.choice(series_database[series_choice])

    print(f"📂 [نوع السلسلة]: {series_choice.upper()}")
    
    if check_ethics(topic):
        print(f"✅ [تدقيق أخلاقي حلال]: اجتاز الفحص بنجاح.")
        print(f"🎯 [العنوان الجذاب]: {topic}")
        print(f"⏰ [الجدولة السحابية]: تم إنتاج المحتوى وجدولته بنجاح (بدون سبام، مقطع بانتظام).")
        print("🚀 [حالة الإمبراطورية السحابية]: جاهز للسيطرة في وقت ذروة الملل والإجازات!")
    else:
        print("❌ [حظر أمني]: تم رفض المحتوى.")

if __name__ == "__main__":
    run_cloud_qazo()
